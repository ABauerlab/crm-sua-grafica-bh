create or replace function public.fiscal_aplicar_ncm(p_sobrescrever boolean default false)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_n integer;
begin
  if not private.dono_ou_servidor() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  with alvo as (
    select c.id, (select r from public.fiscal_ncm_regras r
                   where private.norm_txt(coalesce(c.categoria, '') || ' ' || coalesce(c.descricao, '')) ~ r.padrao
                   order by r.prioridade limit 1) r
      from public.catalogo c
     where p_sobrescrever or c.ncm is null)
  update public.catalogo c set ncm = (a.r).ncm, ncm_revisar = not (a.r).confirmado
    from alvo a where a.id = c.id and a.r is not null;
  get diagnostics v_n = row_count;
  return jsonb_build_object('ok', true, 'atualizados', v_n,
    'a_revisar', (select count(*) from public.catalogo where ncm_revisar),
    'por_ncm', (select jsonb_object_agg(ncm, n) from (select ncm, count(*) n from public.catalogo group by ncm) x));
end $$;
revoke all on function public.fiscal_aplicar_ncm(boolean) from public, anon;
grant execute on function public.fiscal_aplicar_ncm(boolean) to authenticated, service_role;

