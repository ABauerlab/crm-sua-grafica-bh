  id bigint generated by default as identity primary key,
  recebido_em timestamptz not null default now(),
  evento text,
  recurso_id text,
  assinatura_ok boolean not null,
  payload jsonb not null,
  processado_em timestamptz,
  erro text
);
create unique index if not exists bling_eventos_dedup on public.bling_eventos (evento, recurso_id, md5(payload::text));
alter table public.bling_eventos enable row level security;
