-- 5) Preço de marketplace: recebe o mesmo que no site depois da comissão e da taxa fixa ------------
--    P = teto_90( (max(preço da planilha, custo + lucro bruto mínimo) + taxa fixa) / (1 - comissão) )
create or replace function private.preco_marketplace(p_preco numeric, p_custo numeric, p_cfg jsonb)
returns numeric language sql stable set search_path = '' as $$
  select private.teto_90((greatest(p_preco, coalesce(p_custo, 0) + pr.lucro_bruto_minimo) + coalesce((p_cfg ->> 'taxa_fixa')::numeric, 0))
                         / (1 - coalesce((p_cfg ->> 'comissao_pct')::numeric, 0) / 100))
  from public.parametros_comerciais pr where pr.id = 1;
$$;

create or replace view public.catalogo_marketplace with (security_invoker = true) as
  select c.sku, e.ref, e.titulo, e.categoria, e.quantidade, c.unidade, c.ncm, c.ncm_revisar, c.origem_mercadoria,
         c.preco_venda, c.peso_frete_kg, c.embalagem_cm,
         coalesce(c.prazo_cliente_dias, c.prazo_dias_uteis + 1) prazo_site_dias,
         (select jsonb_object_agg(m.key, jsonb_build_object(
             'preco', private.preco_marketplace(c.preco_venda, c.custo, m.value),
             'prazo_fabricacao_dias', c.prazo_dias_uteis + coalesce((m.value ->> 'prazo_extra_dias')::integer, 2)))
            from jsonb_each((select value from public.app_settings where key = 'marketplaces')) m) marketplaces
    from public.catalogo c join public.ecommerce_products e on e.sku = c.sku
   where c.active and c.vendavel and c.preco_venda is not null and e.ativo;
revoke all on public.catalogo_marketplace from anon;
grant select on public.catalogo_marketplace to authenticated;

-- 6) Payload do pedido para o Bling (POST /pedidos/vendas) e pendências fiscais --------------------
create or replace function public.bling_pedido_payload(p_order uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  o public.orders%rowtype; c public.contacts%rowtype; cfg jsonb; v_doc text; v_pend text[] := '{}'; v_itens jsonb; v_serv jsonb; v_total numeric;
  v_cfop text; v_cep text;
begin
  if not private.dono_ou_servidor() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  select * into o from public.orders where id = p_order;
  if not found then return jsonb_build_object('ok', false, 'pendencias', jsonb_build_array('pedido_nao_encontrado')); end if;
  select * into c from public.contacts where id = o.contact_id;
  cfg := (select value from public.app_settings where key = 'bling');
  v_doc := regexp_replace(coalesce(c.document, ''), '\D', '', 'g');
  v_cep := regexp_replace(coalesce(c.cep, ''), '\D', '', 'g');

  if o.payment_status is distinct from 'aprovado' then v_pend := array_append(v_pend, 'pedido_nao_pago'); end if;
  if coalesce(btrim(c.name), '') = '' then v_pend := array_append(v_pend, 'nome'); end if;
  if length(v_doc) not in (11, 14) then v_pend := array_append(v_pend, 'cpf_ou_cnpj'); end if;
  if v_cep !~ '^[0-9]{8}$' then v_pend := array_append(v_pend, 'cep'); end if;
  if coalesce(btrim(c.logradouro), '') = '' then v_pend := array_append(v_pend, 'logradouro'); end if;
  if coalesce(btrim(c.numero), '') = '' then v_pend := array_append(v_pend, 'numero'); end if;
  if coalesce(btrim(c.bairro), '') = '' then v_pend := array_append(v_pend, 'bairro'); end if;
  if coalesce(btrim(c.municipio), '') = '' or c.uf is null then v_pend := array_append(v_pend, 'municipio_uf'); end if;
  if c.codigo_ibge is null then v_pend := array_append(v_pend, 'codigo_ibge'); end if;
  if coalesce(btrim(c.email), '') = '' then v_pend := array_append(v_pend, 'email'); end if;
  if (cfg ->> 'loja_id') is null then v_pend := array_append(v_pend, 'loja_id_do_bling'); end if;

  v_cfop := case when coalesce(c.uf, cfg ->> 'uf_emitente') = cfg ->> 'uf_emitente' then cfg ->> 'cfop_estadual'
                 when c.ie_indicador = 1 then cfg ->> 'cfop_interestadual_contribuinte'
                 else cfg ->> 'cfop_interestadual_nao_contribuinte' end;

  select coalesce(jsonb_agg(jsonb_build_object(
           'codigo', i.code, 'descricao', left(i.description, 120), 'unidade', coalesce(k.unidade, 'UN'),
           'quantidade', i.qty, 'valor', i.unit_price, 'ncm', k.ncm, 'cfop', v_cfop, 'origem', coalesce(k.origem_mercadoria, 0))
           order by i.created_at) filter (where i.code is not null), '[]'::jsonb),
         coalesce(jsonb_agg(jsonb_build_object('descricao', i.description, 'quantidade', i.qty, 'valor', i.unit_price))
           filter (where i.code is null), '[]'::jsonb)
    into v_itens, v_serv
    from public.order_items i left join public.catalogo k on k.sku = i.code
   where i.order_id = p_order;
  if exists (select 1 from jsonb_array_elements(v_itens) x where x ->> 'ncm' is null) then v_pend := array_append(v_pend, 'ncm_de_item'); end if;
  select total into v_total from public.order_financials where order_id = p_order;

  return jsonb_build_object('ok', cardinality(v_pend) = 0, 'pendencias', to_jsonb(v_pend),
    'contato', jsonb_build_object(
      'nome', c.name, 'codigo', 'SG-' || left(c.id::text, 8), 'situacao', 'A',
      'numeroDocumento', nullif(v_doc, ''), 'tipo', coalesce(c.tipo_pessoa, case when length(v_doc) = 14 then 'J' else 'F' end),
      'indicadorIe', coalesce(c.ie_indicador, 9), 'ie', c.inscricao_estadual,
      'celular', c.wa_id, 'email', c.email,
      'endereco', jsonb_build_object('geral', jsonb_build_object('endereco', c.logradouro, 'numero', c.numero, 'complemento', c.complemento,
        'bairro', c.bairro, 'cep', nullif(v_cep, ''), 'municipio', c.municipio, 'uf', c.uf))),
    'pedido', jsonb_build_object(
      'numero', o.number, 'numeroLoja', 'SG-' || o.number, 'data', to_char(coalesce(o.paid_at, o.created_at) at time zone 'America/Sao_Paulo', 'YYYY-MM-DD'),
      'loja', jsonb_build_object('id', (cfg ->> 'loja_id')::bigint, 'nome', cfg ->> 'loja_nome'),
      'contato', jsonb_build_object('id', c.bling_contact_id),
      'itens', v_itens,
      'parcelas', jsonb_build_array(jsonb_build_object('dataVencimento', to_char(coalesce(o.paid_at, now()) at time zone 'America/Sao_Paulo', 'YYYY-MM-DD'),
        'valor', v_total, 'observacoes', 'Pago pelo Mercado Pago (' || coalesce(o.payment_method, 'método não informado') || ')')),
      'observacoes', 'Canal: ' || o.canal || case when o.marketplace_pedido_id is not null then ' (' || o.marketplace_pedido_id || ')' else '' end,
      'observacoesInternas', case when jsonb_array_length(v_serv) > 0 and not coalesce((cfg ->> 'servicos_na_nfe')::boolean, false)
        then 'Serviços fora da NF-e de mercadoria (emitir NFS-e): ' || (select string_agg((s ->> 'descricao') || ' R$ ' || (s ->> 'valor'), '; ') from jsonb_array_elements(v_serv) s) end),
    'servicos', v_serv, 'cfop', v_cfop);
end $$;
revoke all on function public.bling_pedido_payload(uuid) from public, anon;
grant execute on function public.bling_pedido_payload(uuid) to authenticated, service_role;

-- 7) Fila do webhook do Bling (eventos crus; processamento desligado nesta fase) ------------------
