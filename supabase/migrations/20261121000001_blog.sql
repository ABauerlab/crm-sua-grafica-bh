-- E-commerce Fase 8: blog automático do setor gráfico.
-- Pauta: feeds RSS públicos do setor (fonte principal) e NewsAPI só como apoio (desligada por padrão; chave no segredo NEWSAPI_KEY).
-- A Edge Function blog-pautas filtra por assunto, pede ao Gemini um texto PRÓPRIO (nunca cópia), confere e publica sozinha,
-- sempre com crédito e link da fonte. O público lê só posts publicados pelas funções loja_blog_*.

create table if not exists public.blog_fontes (
  id bigint generated by default as identity primary key,
  nome text not null,
  url text not null unique,
  tipo text not null default 'rss' check (tipo in ('rss', 'newsapi')),
  ativo boolean not null default true,
  ultima_leitura timestamptz,
  ultimo_erro text,
  criado_em timestamptz not null default now()
);

create table if not exists public.blog_pautas (
  id bigint generated by default as identity primary key,
  url text not null unique,
  titulo text not null,
  resumo_fonte text,
  fonte_nome text not null,
  publicada_na_fonte timestamptz,
  status text not null default 'nova' check (status in ('nova', 'descartada', 'publicada', 'erro')),
  motivo text,
  relevancia integer,
  tentativas integer not null default 0,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists blog_pautas_novas on public.blog_pautas (publicada_na_fonte desc) where status = 'nova';

create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  titulo text not null,
  resumo text not null,
  corpo text not null,                                   -- markdown simples: parágrafos, "## " subtítulos, "- " listas, **negrito**, links só internos
  categorias jsonb not null default '[]'::jsonb,         -- [{slug, nome}] da vitrine, escolhidas de uma lista válida
  fonte_nome text not null,
  fonte_url text not null,
  pauta_id bigint references public.blog_pautas (id) on delete set null,
  status text not null default 'publicado' check (status in ('publicado', 'oculto')),
  publicado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists blog_posts_publicados on public.blog_posts (publicado_em desc) where status = 'publicado';

alter table public.blog_fontes enable row level security;
alter table public.blog_pautas enable row level security;
alter table public.blog_posts enable row level security;
revoke all on public.blog_fontes, public.blog_pautas, public.blog_posts from anon, authenticated;
grant select, insert, update on public.blog_fontes to authenticated;
grant select on public.blog_pautas to authenticated;
grant select, update on public.blog_posts to authenticated;
drop policy if exists blog_fontes_dono on public.blog_fontes;
create policy blog_fontes_dono on public.blog_fontes for all to authenticated using (private.is_staff()) with check (private.is_staff());
drop policy if exists blog_pautas_dono on public.blog_pautas;
create policy blog_pautas_dono on public.blog_pautas for select to authenticated using (private.is_staff());
drop policy if exists blog_posts_dono on public.blog_posts;
create policy blog_posts_dono on public.blog_posts for all to authenticated using (private.is_staff()) with check (private.is_staff());

-- Leitura pública (site): só publicados e só campos de leitura
create or replace function public.loja_blog_lista(p_pagina integer default 1, p_por_pagina integer default 12)
returns jsonb language sql stable security definer set search_path = '' as $$
  with base as (select * from public.blog_posts where status = 'publicado'),
       pag as (select * from base order by publicado_em desc
               limit least(greatest(coalesce(p_por_pagina, 12), 1), 48)
               offset (greatest(coalesce(p_pagina, 1), 1) - 1) * least(greatest(coalesce(p_por_pagina, 12), 1), 48))
  select jsonb_build_object(
    'total', (select count(*) from base),
    'posts', coalesce((select jsonb_agg(jsonb_build_object('slug', slug, 'titulo', titulo, 'resumo', resumo, 'categorias', categorias,
                         'fonte_nome', fonte_nome, 'publicado_em', publicado_em) order by publicado_em desc) from pag), '[]'::jsonb));
$$;

create or replace function public.loja_blog_post(p_slug text)
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('slug', p.slug, 'titulo', p.titulo, 'resumo', p.resumo, 'corpo', p.corpo, 'categorias', p.categorias,
           'fonte_nome', p.fonte_nome, 'fonte_url', p.fonte_url, 'publicado_em', p.publicado_em, 'atualizado_em', p.atualizado_em,
           'relacionados', coalesce((select jsonb_agg(jsonb_build_object('slug', r.slug, 'titulo', r.titulo, 'resumo', r.resumo, 'publicado_em', r.publicado_em))
                                       from (select * from public.blog_posts r where r.status = 'publicado' and r.id <> p.id
                                              order by r.publicado_em desc limit 3) r), '[]'::jsonb))
    from public.blog_posts p where p.slug = p_slug and p.status = 'publicado';
$$;

create or replace function public.loja_blog_slugs()
returns jsonb language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('s', slug, 'u', atualizado_em) order by publicado_em desc), '[]'::jsonb)
    from public.blog_posts where status = 'publicado';
$$;

revoke all on function public.loja_blog_lista(integer, integer) from public;
revoke all on function public.loja_blog_post(text) from public;
revoke all on function public.loja_blog_slugs() from public;
grant execute on function public.loja_blog_lista(integer, integer) to anon, authenticated, service_role;
grant execute on function public.loja_blog_post(text) to anon, authenticated, service_role;
grant execute on function public.loja_blog_slugs() to anon, authenticated, service_role;

