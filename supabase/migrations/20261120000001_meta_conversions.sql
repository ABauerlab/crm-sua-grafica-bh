-- E-commerce Fase 7: Meta Pixel + Conversions API (CAPI) com deduplicação por event_id.
-- Eventos do navegador (PageView, ViewContent, AddToCart, InitiateCheckout, Lead) chegam pela loja já com os dados pessoais
-- em SHA-256; o Purchase nasce aqui no banco quando o pedido é pago (mesmo caminho do webhook do Mercado Pago).
-- A Edge Function meta-conversions-api esvazia a fila a cada minuto quando META_PIXEL_ID e META_CAPI_TOKEN existem.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.meta_eventos (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event_name text not null check (event_name in ('PageView', 'ViewContent', 'AddToCart', 'InitiateCheckout', 'Lead', 'Purchase', 'Contact')),
  event_time timestamptz not null default now(),
  action_source text not null default 'website' check (action_source in ('website', 'system_generated', 'chat')),
  event_source_url text,
  user_data jsonb not null default '{}'::jsonb,   -- em, ph, external_id em SHA-256; fbp, fbc, client_ip_address e client_user_agent como a Meta pede
  custom_data jsonb not null default '{}'::jsonb,
  pedido_id uuid references public.orders (id) on delete set null,
  status text not null default 'pendente' check (status in ('pendente', 'enviado', 'erro', 'descartado')),
  tentativas integer not null default 0,
  enviado_em timestamptz,
  erro text,
  criado_em timestamptz not null default now()
);
create index if not exists meta_eventos_pendentes on public.meta_eventos (criado_em) where status = 'pendente';
alter table public.meta_eventos enable row level security;
revoke all on public.meta_eventos from anon, authenticated;
grant select on public.meta_eventos to authenticated;
drop policy if exists meta_eventos_dono on public.meta_eventos;
create policy meta_eventos_dono on public.meta_eventos for select to authenticated using (private.is_staff());

create or replace function private.sha256(p text)
returns text language sql immutable set search_path = '' as $$
  select case when nullif(btrim(coalesce(p, '')), '') is null then null
              else encode(extensions.digest(convert_to(lower(btrim(p)), 'UTF8'), 'sha256'), 'hex') end;
$$;

-- Registro de evento vindo da loja (rota /api/v1/eventos). Público, mas só aceita os nomes previstos, ids únicos e
-- user_data que já venha com hash (64 hex) nos campos pessoais.
create or replace function public.meta_evento_registrar(p_evento jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_nome text := p_evento ->> 'event_name'; v_id text := left(p_evento ->> 'event_id', 80); u jsonb := coalesce(p_evento -> 'user_data', '{}'::jsonb); k text;
begin
  if v_nome not in ('PageView', 'ViewContent', 'AddToCart', 'InitiateCheckout', 'Lead', 'Contact') then return jsonb_build_object('ok', false, 'erro', 'evento_invalido'); end if;
  if v_id is null or v_id !~ '^[A-Za-z0-9._:-]{8,80}$' then return jsonb_build_object('ok', false, 'erro', 'event_id_invalido'); end if;
  foreach k in array array['em', 'ph', 'external_id'] loop
    if u ? k and (u ->> k) !~ '^[0-9a-f]{64}$' then u := u - k; end if;
  end loop;
  u := jsonb_strip_nulls(jsonb_build_object('em', u ->> 'em', 'ph', u ->> 'ph', 'external_id', u ->> 'external_id',
        'fbp', left(u ->> 'fbp', 120), 'fbc', left(u ->> 'fbc', 300), 'client_ip_address', left(u ->> 'client_ip_address', 64),
        'client_user_agent', left(u ->> 'client_user_agent', 400)));
  insert into public.meta_eventos (event_id, event_name, event_source_url, user_data, custom_data)
  values (v_id, v_nome, left(p_evento ->> 'event_source_url', 500), u, coalesce(p_evento -> 'custom_data', '{}'::jsonb))
  on conflict (event_id) do nothing;
  return jsonb_build_object('ok', true);
end $$;
revoke all on function public.meta_evento_registrar(jsonb) from public;
grant execute on function public.meta_evento_registrar(jsonb) to anon, authenticated, service_role;

-- Purchase: um por pedido (event_id = purchase-<pedido>), quando o pagamento é aprovado. Pedido de teste não conta.
create or replace function private.meta_purchase_do_pedido()
returns trigger language plpgsql security definer set search_path = '' as $$
declare c public.contacts%rowtype; v_total numeric; v_refs jsonb; v_itens integer;
begin
  if new.payment_status is distinct from 'aprovado' or old.payment_status is not distinct from 'aprovado' or coalesce(new.teste, false) then return new; end if;
  select * into c from public.contacts where id = new.contact_id;
  select total into v_total from public.order_financials where order_id = new.id;
  select coalesce(jsonb_agg(e.ref) filter (where e.ref is not null), '[]'::jsonb), coalesce(sum(i.qty), 0)
    into v_refs, v_itens
    from public.order_items i left join public.ecommerce_products e on e.sku = i.code where i.order_id = new.id;
  insert into public.meta_eventos (event_id, event_name, action_source, event_time, user_data, custom_data, pedido_id)
  values ('purchase-' || new.id::text, 'Purchase', case when new.canal = 'site' then 'website' else 'chat' end, coalesce(new.paid_at, now()),
          jsonb_strip_nulls(jsonb_build_object(
            'ph', private.sha256(regexp_replace(coalesce(c.wa_id, ''), '\D', '', 'g')),
            'em', private.sha256(c.email),
            'external_id', private.sha256(c.id::text),
            'ct', private.sha256(regexp_replace(lower(coalesce(c.municipio, '')), '[^a-z]', '', 'g')),
            'st', private.sha256(lower(c.uf)),
            'zp', private.sha256(regexp_replace(coalesce(c.cep, ''), '\D', '', 'g')),
            'country', private.sha256('br'))),
          jsonb_build_object('currency', 'BRL', 'value', coalesce(v_total, 0), 'content_ids', v_refs, 'content_type', 'product',
                             'num_items', v_itens, 'order_id', 'SG-' || new.number, 'canal', new.canal))
  on conflict (event_id) do nothing;
  return new;
end $$;
drop trigger if exists meta_purchase_do_pedido on public.orders;
create trigger meta_purchase_do_pedido after update of payment_status on public.orders
  for each row execute function private.meta_purchase_do_pedido();

-- Lote para a Edge Function (só service role): pega até N pendentes de até 7 dias (limite da Meta); mais velhos são descartados.
create or replace function public.meta_eventos_lote(p_n integer default 200)
returns setof public.meta_eventos language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  update public.meta_eventos set status = 'descartado', erro = 'mais de 7 dias sem envio'
   where status = 'pendente' and event_time < now() - interval '7 days';
  return query
  update public.meta_eventos m set tentativas = m.tentativas + 1
   where m.id in (select x.id from public.meta_eventos x where x.status = 'pendente' order by x.criado_em limit least(greatest(p_n, 1), 1000) for update skip locked)
  returning m.*;
end $$;
revoke all on function public.meta_eventos_lote(integer) from public, anon, authenticated;
grant execute on function public.meta_eventos_lote(integer) to service_role;

create or replace function public.meta_eventos_resultado(p_ids bigint[], p_ok boolean, p_erro text default null)
returns void language sql security definer set search_path = '' as $$
  update public.meta_eventos
     set status = case when p_ok then 'enviado' when tentativas >= 5 then 'erro' else 'pendente' end,
         enviado_em = case when p_ok then now() end, erro = left(p_erro, 300)
   where id = any (p_ids) and coalesce(auth.role(), '') = 'service_role';
$$;
revoke all on function public.meta_eventos_resultado(bigint[], boolean, text) from public, anon, authenticated;
grant execute on function public.meta_eventos_resultado(bigint[], boolean, text) to service_role;

