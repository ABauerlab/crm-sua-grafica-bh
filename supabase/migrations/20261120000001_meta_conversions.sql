-- Esvazia a fila a cada minuto, só quando há pendente
do $$
begin
  if exists (select 1 from cron.job where jobname = 'meta-conversions') then perform cron.unschedule('meta-conversions'); end if;
  perform cron.schedule('meta-conversions', '* * * * *', $job$
    select net.http_post(
      url := 'https://bhlosshvwmlyzhbghsrc.supabase.co/functions/v1/meta-conversions-api',
      headers := jsonb_build_object('Content-Type', 'application/json',
        'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'cron_secret' limit 1)),
      body := '{}'::jsonb, timeout_milliseconds := 5000)
    where exists (select 1 from public.meta_eventos where status = 'pendente' and event_time > now() - interval '7 days');
  $job$);
end $$;
